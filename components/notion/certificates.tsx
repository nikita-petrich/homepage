/* Permanent, shareable link to the certificate document itself: the
   self-hosted PDF at /zertifikate/<slug>.pdf, or an official external URL when
   not yet hosted. Always opened in a new tab. */
export const certHref = (c: Certificate) =>
  c.externalUrl ?? `/zertifikate/${c.slug}.pdf`;

/* Detail page with the full scope of the certificate. Opens as a dialog via
   the intercepting route and renders standalone on a hard load. */
export const certPageHref = (c: Certificate) => `/zertifikate/${c.slug}`;

const documentLabel = (c: Certificate) =>
  c.externalUrl ? `Auf ${c.issuer} ansehen` : "PDF öffnen";

/* Per-platform pill styling (Notion select colours). */
const issuerPill: Record<Certificate["issuer"], string> = {
  Scrimba: "bg-[var(--pill-green)] text-[#2a6b3a]",
  "Code with Mosh": "bg-[var(--pill-blue)] text-[#24618a]",
  Udemy: "bg-[var(--pill-purple)] text-[#6b4a86]",
};

function IssuerPill({ issuer }: { issuer: Certificate["issuer"] }) {
  return (
    <span
      className={cn(
        "shrink-0 rounded-[4px] px-[7px] py-[2px] text-[11px] font-semibold",
        issuerPill[issuer],
      )}
    >
      {issuer}
    </span>
  );
}

const previewAlt = (c: Certificate) =>
  `Zertifikat „${c.title}“ von ${c.issuer}, ausgestellt ${c.date}`;

/* Certificate "cover": the pre-rendered first page of the PDF (generated by
   scripts/certificate-previews.mjs), shown in full on the warm banner
   background — portrait and landscape certificates both stay readable because
   the page is contained, never cropped. The frame is a little taller than the
   16/9 of the project covers so the portrait pages get room; certificates
   without a self-hosted PDF fall back to a flatter branded band. */
function CertificateCover({
  cert,
  variant,
}: {
  cert: Certificate;
  variant: "card" | "modal";
}) {
  const card = variant === "card";
  // One frame for every card so the covers line up across a gallery row; the
  // dialog gets a wide banner, flatter when there is no page to show.
  const frame = card
    ? "aspect-[4/3]"
    : cert.preview
      ? "aspect-[16/9] sm:aspect-[16/8]"
      : "aspect-[16/6]";

  return (
    <div
      className={cn("relative w-full overflow-hidden", frame)}
      style={{ backgroundImage: bannerBg }}
    >
      <div className="absolute inset-y-0 left-0 z-[1] w-[5px] bg-[var(--accent-o)]" />

      {cert.preview ? (
        <div
          className={cn(
            "absolute inset-0",
            card ? "p-2 pl-[13px]" : "p-4 pl-6 sm:p-5 sm:pl-8",
          )}
        >
          <Image
            src={cert.preview}
            alt={previewAlt(cert)}
            fill
            sizes={card ? "(max-width: 640px) 100vw, 340px" : "(max-width: 720px) 100vw, 680px"}
            className="object-contain drop-shadow-[0_2px_10px_rgba(15,15,15,0.18)]"
          />
        </div>
      ) : (
        <div className="flex h-full flex-col items-center justify-center gap-1.5 px-3 text-center">
          <Award size={30} strokeWidth={1.6} className="text-[var(--accent-o)]" />
          <span className="text-[10px] font-semibold tracking-[0.14em] text-[#6b614e] uppercase">
            {cert.issuer}
          </span>
        </div>
      )}
    </div>
  );
}

/* The scope fields join the search surface: a query like "Firebase", "MCP" or
   "Olof Paulson" should find the certificate that covers it. */
const certificateSearchText = (c: Certificate) =>
  [
    c.title,
    c.issuer,
    c.cat,
    c.tags.join(" "),
    c.summary,
    c.facts?.map((f) => f.value).join(" ") ?? "",
    c.outcomes?.join(" ") ?? "",
    c.curriculum
      ?.map((s) => `${s.title} ${s.lessons?.join(" ") ?? ""}`)
      .join(" ") ?? "",
  ].join(" ");
const certificateSortKey = (c: Certificate) => c.sort;

/* Table view: same target (the detail dialog) and analytics as the gallery
   cards, laid out as a CSS grid so cells stay simple <Link> children. */
const CERTIFICATE_COLS =
  "grid-cols-[minmax(200px,1.8fr)_minmax(120px,0.9fr)_minmax(100px,0.7fr)_minmax(140px,1.1fr)_28px]";

